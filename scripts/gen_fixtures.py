#!/usr/bin/env python3
"""Turn eth_getProof fixtures into Fe modules the tests import.

For every fixtures/<dir>/<name>.json this writes ingots/conformance/src/<dir>_<name>.fe
with the block header (RLP, re-encoded from the JSON fields and checked against
the block hash), the state root, the account and each storage slot, and both
proof layouts: packed (nodes end to end) and ABI bytes[].

Usage: gen_fixtures.py fixtures/mainnet/usdc.json [...]
"""
import json
import pathlib
import sys

from eth_hash.auto import keccak

# Header fields in RLP order; fields after the first fifteen are added by forks.
HEADER_FIELDS = [
    ("parentHash", "bytes"), ("sha3Uncles", "bytes"), ("miner", "bytes"), ("stateRoot", "bytes"),
    ("transactionsRoot", "bytes"), ("receiptsRoot", "bytes"), ("logsBloom", "bytes"),
    ("difficulty", "int"), ("number", "int"), ("gasLimit", "int"), ("gasUsed", "int"),
    ("timestamp", "int"), ("extraData", "bytes"), ("mixHash", "bytes"), ("nonce", "bytes"),
    ("baseFeePerGas", "int"), ("withdrawalsRoot", "bytes"), ("blobGasUsed", "int"),
    ("excessBlobGas", "int"), ("parentBeaconBlockRoot", "bytes"), ("requestsHash", "bytes"),
    # Amsterdam: EIP-7928 block access list hash, EIP-7843 slot number.
    ("blockAccessListHash", "bytes"), ("slotNumber", "int"),
]


def rlp_bytes(b: bytes) -> bytes:
    if len(b) == 1 and b[0] < 0x80:
        return b
    return rlp_len(len(b), 0x80) + b


def rlp_len(n: int, offset: int) -> bytes:
    if n < 56:
        return bytes([offset + n])
    nb = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([offset + 55 + len(nb)]) + nb


def rlp_list(items) -> bytes:
    payload = b"".join(items)
    return rlp_len(len(payload), 0xC0) + payload


def header_rlp(block: dict) -> bytes:
    items = []
    for name, kind in HEADER_FIELDS:
        if name not in block:
            break
        raw = block[name]
        if kind == "int":
            v = int(raw, 16)
            items.append(rlp_bytes(v.to_bytes((v.bit_length() + 7) // 8, "big")))
        else:
            items.append(rlp_bytes(bytes.fromhex(raw[2:])))
    enc = rlp_list(items)
    assert "0x" + keccak(enc).hex() == block["hash"], "header re-encoding does not match the block hash"
    return enc


def fe_list(nodes) -> str:
    parts = ",\n        ".join(f'decode_hex("{n[2:]}").unwrap()' for n in nodes)
    return f"dyn_array_from([\n        {parts},\n    ])"


def module(path: pathlib.Path) -> str:
    d = json.loads(path.read_text())
    block, proof = d["block"], d["proof"]
    head = header_rlp(block)
    out = [
        f"// Generated by scripts/gen_fixtures.py from {path.as_posix()}. Do not edit.",
        f"// Chain {int(d['chainId'], 16)}, block {int(block['number'], 16)}.",
        "use core::text::decode_hex",
        "use std::abi::{Bytes, DynArray, DynString, dyn_array_from}",
        "",
        f"pub const BLOCK_NUMBER: u256 = {int(block['number'], 16)}",
        f"pub const BLOCK_HASH: u256 = {block['hash']}",
        f"pub const STATE_ROOT: u256 = {block['stateRoot']}",
        f"pub const TIMESTAMP: u256 = {int(block['timestamp'], 16)}",
        f"pub const ACCOUNT: Address = Address::new({proof['address']})",
        f"pub const STORAGE_ROOT: u256 = {proof['storageHash']}",
        f"pub const NONCE: u256 = {int(proof['nonce'], 16)}",
        f"pub const BALANCE: u256 = {int(proof['balance'], 16)}",
        f"pub const CODE_HASH: u256 = {proof['codeHash']}",
        f"pub const SLOT_COUNT: usize = {len(proof['storageProof'])}",
        "",
        f'pub fn header() -> DynString {{ "{head.hex()}" }}',
        f"pub const HEADER_LEN: usize = {len(head)}",
        "",
        f'pub fn account_packed() -> DynString {{ "{"".join(n[2:] for n in proof["accountProof"])}" }}',
        f"pub fn account_list() -> DynArray<Bytes> {{\n    {fe_list(proof['accountProof'])}\n}}",
    ]
    for i, s in enumerate(proof["storageProof"]):
        key = int(s["key"], 16)
        out += [
            "",
            f"pub const SLOT{i}: u256 = {hex(key)}",
            f"pub const SLOT{i}_VALUE: u256 = {s['value']}",
            f'pub fn slot{i}_packed() -> DynString {{ "{"".join(n[2:] for n in s["proof"])}" }}',
        ]
        if s["proof"]:
            out.append(f"pub fn slot{i}_list() -> DynArray<Bytes> {{\n    {fe_list(s['proof'])}\n}}")
        else:
            out.append(f"pub fn slot{i}_list() -> DynArray<Bytes> {{\n    DynArray::empty()\n}}")
    return "\n".join(out) + "\n"


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    for arg in sys.argv[1:]:
        path = pathlib.Path(arg)
        name = f"{path.parent.name}_{path.stem}".replace("-", "_")
        dest = root / "ingots" / "conformance" / "src" / f"{name}.fe"
        dest.write_text(module(path.relative_to(root) if path.is_absolute() else path), newline="\n")
        print(dest.relative_to(root).as_posix())


if __name__ == "__main__":
    main()
