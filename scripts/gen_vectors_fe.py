#!/usr/bin/env python3
"""Turn the synthetic proof vectors into Fe tests.

Reads fixtures/synthetic/<group>.json (written by scripts/vectors/gen.mjs) and
writes ingots/conformance/src/vectors_<group>.fe: one #[test] per case, each a
call to `vector::check`. The same tests run on the EVM and natively.
"""
import json
import pathlib

GROUPS = ["inclusion", "inline", "exclusion", "invalid"]
ERRORS = {"Malformed": 1, "HashMismatch": 2, "MissingNode": 3, "ExtraNodes": 4, "BadReference": 5}
FOUND, ABSENT = 0, 100


def expect_code(expect: dict):
    if "error" in expect:
        return ERRORS[expect["error"]], 0
    if expect["found"]:
        return FOUND, int(expect["word"], 16)
    return ABSENT, 0


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    for group in GROUPS:
        cases = json.loads((root / "fixtures" / "synthetic" / f"{group}.json").read_text())
        out = [
            f"// Generated by scripts/gen_vectors_fe.py from fixtures/synthetic/{group}.json. Do not edit.",
            "use ingot::vector::check",
            "",
        ]
        for i, case in enumerate(cases):
            code, word = expect_code(case["expect"])
            proof = "".join(node[2:] for node in case["proof"])
            out += [
                f"// {case['name']}",
                "#[test]",
                f"fn {group}_{i:03}() {{",
                f"    check(root: {case['root']}, key: {case['key']}, path: {case['path']}, proof: \"{proof}\", expect: {code}, word: {hex(word)})",
                "}",
                "",
            ]
        dest = root / "ingots" / "conformance" / "src" / f"vectors_{group}.fe"
        dest.write_text("\n".join(out), newline="\n")
        print(f"{dest.relative_to(root).as_posix()}: {len(cases)} cases")


if __name__ == "__main__":
    main()
